#!/usr/bin/env node
/**
 * generate-env-config.js
 *
 * Reads public env vars from .env.local and writes public/env-config.js so
 * that local development uses the exact same mechanism as production:
 * the browser reads window.__ENV__ instead of NEXT_PUBLIC_* static replacements.
 *
 * Run automatically via the "predev" script in package.json before `next dev`.
 * In production, scripts/docker-entrypoint.sh does the equivalent at container startup.
 */

const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')

// Parse .env.local manually (dotenv is a devDependency but we keep this
// dependency-free so it works even before `pnpm install` completes).
function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {}
  const lines = fs.readFileSync(filePath, 'utf8').split('\n')
  const result = {}
  for (const line of lines) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eqIndex = trimmed.indexOf('=')
    if (eqIndex === -1) continue
    const key = trimmed.slice(0, eqIndex).trim()
    const raw = trimmed.slice(eqIndex + 1).trim()
    // Strip surrounding quotes if present
    const value =
      (raw.startsWith('"') && raw.endsWith('"')) ||
      (raw.startsWith("'") && raw.endsWith("'"))
        ? raw.slice(1, -1)
        : raw
    result[key] = value
  }
  return result
}

const localEnv = parseEnvFile(path.join(root, '.env.local'))

// Merge with process.env so vars already exported in the shell take precedence
const merged = { ...localEnv, ...process.env }

const env = {
  CIVITAS_API_URL:      merged.CIVITAS_API_URL      ?? '',
  MAPBOX_ACCESS_TOKEN:  merged.MAPBOX_ACCESS_TOKEN  ?? '',
  ENABLE_CHAMADOS:      merged.ENABLE_CHAMADOS      ?? 'false',
  ENABLE_IMPERSONATION: merged.ENABLE_IMPERSONATION ?? 'false',
  APP_URL:              merged.APP_URL               ?? '',
}

const content =
  '// Generated by scripts/generate-env-config.js — do not edit or commit.\n' +
  'window.__ENV__ = ' +
  JSON.stringify(env, null, 2) +
  ';\n'

fs.writeFileSync(path.join(root, 'public', 'env-config.js'), content)
console.log('[env-config] public/env-config.js written from .env.local')
