import type { BusStop, CollectionPoint, School } from '@/models/entities'
import {
  getCameraOrigin,
  getCollectionPointOrigin,
} from '@/utils/collection-point-origin'
import {
  getPointClusterLayerPrefix,
  isPointClusterLayerId,
  POINT_CLUSTER_GROUPS,
  POINT_LAYER_IDS,
} from '@/utils/point-layer-config'
import {
  busStopAdapter,
  createCollectionPointSources,
  preparePointSource,
  schoolAdapter,
} from '@/utils/point-layer-sources'

describe('point source domain adapters', () => {
  it.each([
    [' civitas ', 'CIVITAS'],
    ['GABRIEL', 'GABRIEL'],
    [' gAbRiEl ', 'GABRIEL'],
    ['CET-Rio', 'CETRIO'],
    ['cetrio', 'CETRIO'],
    [' Unknown Company ', 'Unknown Company'],
    [null, 'Origem não informada'],
  ])(
    'normalizes LPR origin %s consistently for icons and counts',
    (input, expected) => {
      expect(getCollectionPointOrigin(input)).toBe(expected)
    },
  )

  it.each([
    [' dc3 ', 'DC3'],
    ['tixi', 'TIXI'],
    ['', 'Origem não informada'],
  ])('normalizes camera origin %s', (input, expected) => {
    expect(getCameraOrigin(input)).toBe(expected)
  })

  it('keeps every LPR origin in one source with canonical origins and original objects', () => {
    const point: CollectionPoint = {
      cetRioCode: 'A',
      company: ' cIvItAs ',
      longitude: -43.2,
      latitude: -22.9,
      location: null,
      district: null,
      direction: null,
      lane: null,
      lastDetectionTime: null,
      activeInLast24Hours: true,
    }
    const gabriel = { ...point, cetRioCode: 'B', company: ' gabriel ' }
    const sources = createCollectionPointSources([point, gabriel])

    expect(sources).toHaveLength(1)
    const [civitasPoint, gabrielPoint] = sources[0].points
    expect(civitasPoint.point).toBe(point)
    expect(civitasPoint.origin).toBe('CIVITAS')
    expect(gabrielPoint.point).toBe(gabriel)
    expect(gabrielPoint.origin).toBe('GABRIEL')
  })

  it('uses domain IDs for schools and bus stops instead of positional fallbacks', () => {
    const school: School = {
      objectid: 42,
      cre: 1,
      designacao: 2,
      denominacao: 'School',
      latitude: 0,
      longitude: 0,
      tipo: 'Municipal',
    }
    const stop: BusStop = {
      id_parada: 'BUS-7',
      nome_parada: 'Stop',
      data_versao: '',
      latitude: 0,
      longitude: 0,
    }
    const schoolSource = preparePointSource(
      POINT_LAYER_IDS.schools,
      [school],
      schoolAdapter,
    )
    const busSource = preparePointSource(
      POINT_LAYER_IDS.busStops,
      [stop],
      busStopAdapter,
    )

    expect(schoolSource.points[0]).toEqual(
      expect.objectContaining({
        id: 'schools:42',
        coordinates: [0, 0],
        point: school,
      }),
    )
    expect(busSource.points[0]).toEqual(
      expect.objectContaining({
        id: 'BusStops:BUS-7',
        coordinates: [0, 0],
        point: stop,
      }),
    )
  })

  it('recognizes only the cluster layer IDs generated by the group registry', () => {
    for (const group of POINT_CLUSTER_GROUPS) {
      expect(
        isPointClusterLayerId(
          `${getPointClusterLayerPrefix(group.id)}-circles`,
        ),
      ).toBe(true)
      expect(
        isPointClusterLayerId(`${getPointClusterLayerPrefix(group.id)}-counts`),
      ).toBe(true)
    }
    expect(isPointClusterLayerId('point-clusters-unknown-circles')).toBe(false)
    expect(isPointClusterLayerId(POINT_LAYER_IDS.radars)).toBe(false)
  })
})
